use anyhow::Result;
use serde_yaml::{Mapping, Value};
use tracing::{instrument, warn};

use crate::{
    client::ports::get_clash_external_port,
    config::core::Config,
    utils::{dirs, help},
};

#[derive(Default, Debug, Clone)]
pub struct IClashTemp(pub Mapping);

impl IClashTemp {
    pub fn template() -> Self {
        let mut map = Mapping::new();

        map.insert("mixed-port".into(), 7890.into());
        map.insert("log-level".into(), "info".into());
        map.insert("allow-lan".into(), false.into());
        map.insert("mode".into(), "rule".into());
        #[cfg(debug_assertions)]
        map.insert("external-controller".into(), "127.0.0.1:9872".into());
        #[cfg(not(debug_assertions))]
        map.insert("external-controller".into(), "127.0.0.1:17650".into());
        map.insert(
            "secret".into(),
            // todo: logging uuid::Uuid::new_v4().to_string().to_lowercase().into(), // generate a uuid v4 as default secret to secure the communication between clash and the client
            "chimera".into(),
        );
        #[cfg(feature = "default-meta")]
        map.insert("unified-delay".into(), true.into());
        #[cfg(feature = "default-meta")]
        map.insert("tcp-concurrent".into(), true.into());
        map.insert("ipv6".into(), false.into());

        Self(map)
    }

    pub fn new() -> Self {
        match dirs::clash_guard_overrides_path().and_then(|path| help::read_merge_mapping(&path)) {
            Ok(map) => Self(Self::guard(map)),
            Err(err) => {
                log::error!(target: "app", "{err:?}");
                Self::template()
            }
        }
    }

    fn guard(mut config: Mapping) -> Mapping {
        let port = Self::guard_mixed_port(&config);
        let ctrl = Self::guard_server_ctrl(&config);

        config.insert("mixed-port".into(), port.into());
        config.insert("external-controller".into(), ctrl.into());
        config
    }

    pub fn guard_mixed_port(config: &Mapping) -> u16 {
        ClashInfo::guard_mixed_port(config)
    }

    pub fn guard_server_ctrl(config: &Mapping) -> String {
        ClashInfo::guard_server_ctrl(config)
    }

    #[instrument]
    pub fn prepare_external_controller_port(&mut self) -> Result<()> {
        let strategy = Config::verge()
            .latest()
            .get_external_controller_port_strategy();

        let server = self.get_client_info().server;
        let (server_ip, server_port) = server.split_once(':').unwrap_or(("127.0.0.1", "9090"));
        let server_port = server_port.parse::<u16>().unwrap_or(9090);
        let port = get_clash_external_port(&strategy, server_port)?;

        if port != server_port {
            let new_server = format!("{server_ip}:{port}");
            log::warn!("The external controller port has been changed to {new_server}");
            let mut map = Mapping::new();
            map.insert("external-controller".into(), new_server.into());
            self.patch_config(map);
        }
        Ok(())
    }

    pub fn get_client_info(&self) -> ClashInfo {
        ClashInfo::from_mapping(&self.0)
    }

    pub fn guard_client_ctrl(config: &Mapping) -> String {
        ClashInfo::guard_client_ctrl(config)
    }

    pub fn get_mixed_port(&self) -> u16 {
        Self::guard_mixed_port(&self.0)
    }

    pub fn patch_config(&mut self, patch: Mapping) {
        for (key, value) in patch.into_iter() {
            if !matches!(value, Value::Null) {
                self.0.insert(key, value);
            } else {
                warn!(
                    "the value of {key:?} is null, it will be ignored to avoid deleting the existing config"
                );
            }
        }
    }

    pub fn save_config(&self) -> Result<()> {
        tracing::debug!(
            "saving clash config: {:?} and the value non null guaranted by patch_config",
            self.0
        );
        help::save_yaml(
            &dirs::clash_guard_overrides_path()?,
            &self.0,
            Some("# Generated by Clash Chimera clash_guard_overrides_path"),
        )
    }
}

// The public controller-info DTO is ref-owned in the independent core.
// Keep the existing module path for Agent, IPC, legacy UI, and runtime facades.
pub use chimera_core::client::clash_info::ClashInfo;

#[cfg(test)]
mod core_clash_info_contract_tests {
    use super::{ClashInfo, IClashTemp};

    #[test]
    fn old_yaml_projection_and_core_owned_dto_keep_identical_ipc_fields() {
        let info = IClashTemp::template().get_client_info();
        let wire = serde_json::to_value(&info).unwrap();
        assert_eq!(wire["port"], 7890);
        assert_eq!(wire["secret"], "chimera");
        assert!(wire["server"].as_str().unwrap().starts_with("127.0.0.1:"));
        assert_eq!(wire.as_object().unwrap().len(), 3);
        let typed: ClashInfo = serde_json::from_value(wire).unwrap();
        assert_eq!(typed, info);
    }
}

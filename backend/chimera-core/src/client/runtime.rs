#[cfg(test)]
mod tests {
    use super::*;
    use crate::client::ports::test_runtime_receipt;

    #[test]
    fn cloned_store_shares_revision_sequence_and_confirmed_owner() {
        let store = RuntimeSnapshotStore::default();
        let clone = store.clone();
        assert_eq!(store.allocate_revision().unwrap().get(), 1);
        assert_eq!(clone.allocate_revision().unwrap().get(), 2);
        let receipt = Arc::new(test_runtime_receipt(Default::default()));
        store.publish_confirmed(receipt.clone());
        assert!(Arc::ptr_eq(
            &receipt,
            &clone.accepted_confirmed_receipt().unwrap()
        ));
        clone.invalidate_confirmed();
        assert!(store.accepted_confirmed_receipt().is_none());
        assert!(Arc::ptr_eq(&receipt, &store.confirmed_receipt().unwrap()));
    }

    #[test]
    fn invalidated_receipt_cannot_publish_applied_product() {
        let store = RuntimeSnapshotStore::default();
        let product = Arc::new(RuntimeSnapshot::new(
            store.allocate_revision().unwrap(),
            ClashCore::Mihomo,
            b"mode: rule\n".to_vec(),
            Mapping::new(),
        ));
        let mut receipt = test_runtime_receipt(Default::default());
        receipt.revision = product.revision;
        receipt.config_digest = chimera_core_manager::payload_digest(product.product_bytes());
        receipt.artifact = Some(product.clone());
        store.publish_confirmed(Arc::new(receipt));
        store.publish_promoted(product.clone());
        store.invalidate_confirmed();
        assert!(store.publish_applied(product).is_err());
        assert!(store.snapshot().applied.is_none());
    }
}

/// Upstream's typed atomic publication boundary. Reconciler invokes this
/// only after Core confirms an apply; building a candidate never publishes.
pub async fn write_product(
    product: &std::path::Path,
    bytes: Vec<u8>,
) -> std::result::Result<(), chimera_contracts::publish::PublishRuntimeError> {
    use chimera_contracts::{profiles::error::ErrorPath, publish::PublishRuntimeError};
    if let Some(parent) = product.parent() {
        tokio::fs::create_dir_all(parent).await.map_err(|source| {
            PublishRuntimeError::CreateRuntimeDirectory {
                path: ErrorPath::from(parent),
                source,
            }
        })?;
    }
    let path = product.to_path_buf();
    let written = tokio::task::spawn_blocking(move || {
        atomicwrites::AtomicFile::new(&path, atomicwrites::OverwriteBehavior::AllowOverwrite)
            .write(|file| std::io::Write::write_all(file, &bytes))
    })
    .await;
    let written = written.unwrap_or_else(|error| {
        // The worker failed before reporting its own typed atomic-write error.
        // Preserve the source and do not claim publication succeeded.
        Err(atomicwrites::Error::Internal(std::io::Error::other(error)))
    });
    written.map_err(|source| PublishRuntimeError::WriteRuntimeConfig {
        path: ErrorPath::from(product),
        source,
    })
}

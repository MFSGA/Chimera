#[derive(Serialize, Deserialize, Default, Debug, Clone, Copy, PartialEq, Eq, specta::Type)]
#[serde(rename_all = "snake_case")]
pub enum ScriptType {
    #[default]
    #[serde(rename = "javascript")]
    JavaScript,
    Lua,
}

/// Whether the user wants a core running at all.
///
/// A stopped core is an intent, not a failure: an ordinary save must not start
/// one behind the user's back just because it has something to apply.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum CoreRunIntent {
    Running,
    StoppedByUser,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub struct RuntimeRevision(u64);

impl RuntimeRevision {
    #[cfg(any(test, feature = "test-support"))]
    pub fn from_raw(value: u64) -> Self {
        Self(value)
    }

    pub fn get(self) -> u64 {
        self.0
    }
}

#[derive(Debug, Default)]
pub struct RuntimeRebuildGate(tokio::sync::Mutex<()>);

impl RuntimeRebuildGate {
    pub async fn lock(&self) -> tokio::sync::MutexGuard<'_, ()> {
        self.0.lock().await
    }

    pub fn is_locked(&self) -> bool {
        self.0.try_lock().is_err()
    }
}

// Ref's shared session allocator: cloned preparation/build owners consume one
// revision sequence, never independent counter copies. Chimera still returns
// an explicit error on overflow until its RuntimeError port is migrated.
#[derive(Debug, Clone, Default)]
pub struct RuntimeRevisionAllocator(Arc<AtomicU64>);

impl RuntimeRevisionAllocator {
    /// Ref's constructor; Chimera retains a fallible allocation result until
    /// the RuntimeRevisionAllocator representation migrates with its owner.
    pub fn new() -> Self {
        Self::default()
    }

    pub fn allocate(&self) -> Result<RuntimeRevision> {
        let previous = self
            .0
            .fetch_update(Ordering::Relaxed, Ordering::Relaxed, |value| {
                value.checked_add(1)
            })
            .map_err(|_| anyhow::anyhow!("runtime revision space exhausted"))?;
        Ok(RuntimeRevision(previous + 1))
    }
}

const PRODUCT_HEADER: &str = "# Generated by Clash Chimera\n\n";

/// Serialize the generated product once, including the upstream-style header.
pub fn render_runtime_bytes(config: &Mapping) -> Result<Vec<u8>, serde_yaml::Error> {
    let yaml = serde_yaml::to_string(config)?;
    Ok([PRODUCT_HEADER.as_bytes(), yaml.as_bytes()].concat())
}

#[derive(Debug, Clone)]
pub struct RuntimeSnapshotData {
    pub config_text: Arc<str>,
    pub config: Mapping,
    pub exists_keys: Vec<String>,
    pub postprocessing_output: PostProcessingOutput,
    pub inspection: Arc<super::runtime_inspection::RuntimeInspectionData>,
}

#[derive(Debug, Clone)]
pub struct RuntimeSnapshot {
    pub inspection_id: String,
    pub revision: RuntimeRevision,
    pub target_core: ClashCore,
    pub product_sha256: [u8; 32],
    pub config: Mapping,
    pub exists_keys: Vec<String>,
    pub postprocessing_output: PostProcessingOutput,
    config_text: Arc<str>,
    pub inspection: Arc<super::runtime_inspection::RuntimeInspectionData>,
    /// Core-reported effective document is an ephemeral view, never stored in the build graph.
    pub effective: Option<Arc<super::runtime_inspection::EffectiveInspection>>,
}

impl RuntimeSnapshot {
    pub fn from_data(
        revision: RuntimeRevision,
        target_core: ClashCore,
        data: RuntimeSnapshotData,
    ) -> Self {
        let product_sha256 = Sha256::digest(data.config_text.as_bytes()).into();
        Self {
            inspection_id: nanoid::nanoid!(),
            revision,
            target_core,
            product_sha256,
            config: data.config,
            exists_keys: data.exists_keys,
            postprocessing_output: data.postprocessing_output,
            config_text: data.config_text,
            inspection: data.inspection,
            effective: None,
        }
    }

    #[cfg(any(test, feature = "test-support"))]
    pub fn new(
        revision: RuntimeRevision,
        target_core: ClashCore,
        product_bytes: Vec<u8>,
        config: Mapping,
    ) -> Self {
        Self::new_with_transform_output(
            revision,
            target_core,
            product_bytes,
            config,
            PostProcessingOutput::default(),
        )
    }

    #[cfg(any(test, feature = "test-support"))]
    pub fn new_with_transform_output(
        revision: RuntimeRevision,
        target_core: ClashCore,
        product_bytes: Vec<u8>,
        config: Mapping,
        transform_output: PostProcessingOutput,
    ) -> Self {
        Self::new_with_transform_output_and_exists_keys(
            revision,
            target_core,
            product_bytes,
            config,
            transform_output,
            Vec::new(),
        )
    }

    #[cfg(any(test, feature = "test-support"))]
    pub fn new_with_transform_output_and_exists_keys(
        revision: RuntimeRevision,
        target_core: ClashCore,
        product_bytes: Vec<u8>,
        config: Mapping,
        transform_output: PostProcessingOutput,
        exists_keys: Vec<String>,
    ) -> Self {
        Self::from_data(
            revision,
            target_core,
            RuntimeSnapshotData {
                config_text: String::from_utf8(product_bytes)
                    .expect("runtime fixture must be UTF-8")
                    .into(),
                config,
                exists_keys,
                postprocessing_output: transform_output,
                inspection: Arc::new(super::runtime_inspection::RuntimeInspectionData::bare()),
            },
        )
    }

    #[cfg(any(test, feature = "test-support"))]
    pub fn new_with_transform_output_and_inspection(
        revision: RuntimeRevision,
        target_core: ClashCore,
        product_bytes: Vec<u8>,
        config: Mapping,
        transform_output: PostProcessingOutput,
        inspection: super::runtime_inspection::RuntimeInspectionData,
    ) -> Self {
        Self::new_with_transform_output_and_inspection_and_exists_keys(
            revision,
            target_core,
            product_bytes,
            config,
            transform_output,
            inspection,
            Vec::new(),
        )
    }

    #[cfg(any(test, feature = "test-support"))]
    pub fn new_with_transform_output_and_inspection_and_exists_keys(
        revision: RuntimeRevision,
        target_core: ClashCore,
        product_bytes: Vec<u8>,
        config: Mapping,
        transform_output: PostProcessingOutput,
        inspection: super::runtime_inspection::RuntimeInspectionData,
        exists_keys: Vec<String>,
    ) -> Self {
        Self::from_data(
            revision,
            target_core,
            RuntimeSnapshotData {
                config_text: String::from_utf8(product_bytes)
                    .expect("runtime fixture must be UTF-8")
                    .into(),
                config,
                exists_keys,
                postprocessing_output: transform_output,
                inspection: Arc::new(inspection),
            },
        )
    }

    pub fn product_bytes(&self) -> &[u8] {
        self.config_text.as_bytes()
    }

    /// The same allocation submitted to Core and written to the product.
    pub fn config_text(&self) -> Arc<str> {
        self.config_text.clone()
    }

    /// YAML view of the built document (without the generated-file header).
    pub fn runtime_yaml(&self) -> &str {
        self.config_text
            .strip_prefix(PRODUCT_HEADER)
            .unwrap_or(&self.config_text)
    }

    pub fn clash_info(&self) -> ClashInfo {
        ClashInfo::from_mapping(&self.config)
    }

    pub fn identity_eq(&self, other: &Self) -> bool {
        self.revision == other.revision
            && self.target_core == other.target_core
            && self.product_sha256 == other.product_sha256
    }

    pub fn with_revision(&self, revision: RuntimeRevision) -> Self {
        Self::from_data(
            revision,
            self.target_core,
            RuntimeSnapshotData {
                config_text: self.config_text.clone(),
                config: self.config.clone(),
                exists_keys: self.exists_keys.clone(),
                postprocessing_output: self.postprocessing_output.clone(),
                inspection: self.inspection.clone(),
            },
        )
    }
}

/// What the selected core host confirmed it applied. Keep the exact submitted
/// bytes and host settings here: a Profile transaction may have to restore this
/// runtime even when the previous Profile source now describes something else.
/// `artifact` is Chimera's derived UI snapshot paired with the receipt; it is
/// not evidence that the core accepted the document.
#[derive(Debug, Clone)]
pub struct RuntimeApplyReceipt {
    pub revision: RuntimeRevision,
    pub config_text: Arc<str>,
    pub config_digest: String,
    pub target_core: ClashCore,
    pub core_spec: chimera_core_manager::CoreSpec,
    pub host: crate::actor_v2::endpoint::ExecutionHost,
    pub run_intent: CoreRunIntent,
    pub local_ipc: chimera_core_manager::LocalIpcSettings,
    pub applied_revision: chimera_ipc::api::status::ConfigRevisionInfo,
    pub instance_id: Option<String>,
    pub controller_generation: Option<u64>,
    /// The Profile-backed source identity this runtime was built from, when
    /// the caller captured the complete committed target.
    pub target: Option<String>,
    pub ports: super::ports::CandidatePortBindings,
    pub artifact: Option<Arc<RuntimeSnapshot>>,
}

impl RuntimeApplyReceipt {
    pub fn confirms(
        &self,
        host: crate::actor_v2::endpoint::ExecutionHost,
        status: &crate::actor_v2::endpoint::CoreStatusSnapshot,
    ) -> bool {
        super::runtime_recovery::matches_endpoint_apply(self, host, status)
    }

    pub fn confirms_projection(&self, status: &crate::actor_v2::CoreStatusProjection) -> bool {
        super::runtime_recovery::confirmed_apply_kind(
            self,
            &super::runtime_recovery::ObservedRuntime::from_status(status),
        )
        .is_some()
    }
}

